#!/usr/bin/env python3
"""Generate every contract of this bundle from tests/reference/op_specs.py.

Output (all generated, never edited by hand):

* ``contracts/operation_manifest.yaml`` — every operation
* ``contracts/step_ui_manifest.yaml``   — the builder form of every operation
* ``contracts/artifact_policies.yaml``  — file inputs and outputs
* ``ui/actions/actions.yaml``           — the same-id workflow-visible actions
* ``ui/pages/odoo-api.yaml``, ``ui/pages/changelog.yaml`` — via ``build_ui_pages.py``
* ``extension.yaml`` ``external_effects`` block

Run from the bundle root:  python3 tests/reference/build_contracts.py
``tests/test_contracts.py`` fails when the committed files drift from this output.
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

import yaml

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))

import build_ui_pages  # noqa: E402
import op_specs  # noqa: E402

CONNECTION_TYPE_ID = "odoo"
CATEGORY = "finance"
CHANNEL = "odoo_external_api"
GENERATED_HEADER = (
    "# Generated by tests/reference/build_contracts.py from tests/reference/op_specs.py.\n"
    "# Do not edit by hand: tests/test_contracts.py fails when this file drifts.\n"
)
UPLOAD_BINDING = "odoo_upload"
DOWNLOAD_BINDING = "odoo_attachment"
EXPORT_BINDING = "odoo_export"
MAX_UPLOAD_BYTES = 25 * 1024 * 1024
MAX_DOWNLOAD_BYTES = 40 * 1024 * 1024
MAX_EXPORT_BYTES = 200 * 1024 * 1024
DOWNLOAD_CONTENT_TYPE = "application/octet-stream"
DOWNLOAD_FILENAME = "odoo-attachment.bin"
EXPORT_CONTENT_TYPE = "application/x-ndjson"
EXPORT_FILENAME = "odoo-export.jsonl"
FILE_FIELD_HELP = "A workflow file, e.g. the invoice PDF from an earlier step, up to 25 MB."
TEXTAREA_INPUTS = {"notes"}

BASE_ERRORS = [
    "invalid_payload",
    "invalid_host_envelope",
    "invalid_connection",
    "unsupported_operation",
    "unsupported_version",
    "internal_error",
]
TRANSPORT_ERRORS = [
    "authentication_failed",
    "access_denied",
    "not_found",
    "conflict",
    "rate_limited",
    "upstream_validation_failed",
    "upstream_failure",
    "invalid_response",
    "response_too_large",
    "timeout",
    "connection_failed",
    "redirect_rejected",
    "blocked_address",
]


def effect_outputs() -> list[dict[str, Any]]:
    return [
        {"name": "external_effect_status", "value_type": "text", "schema": {"type": "string"}},
        {
            "name": "definitely_no_external_effect",
            "value_type": "boolean",
            "schema": {"type": "boolean"},
        },
    ]


def errors_for(spec: dict[str, Any]) -> list[str]:
    codes = [*BASE_ERRORS, *TRANSPORT_ERRORS]
    if spec["kind"] == "action":
        codes.append("timeout_unknown")
    if spec.get("module") or spec["operation_id"] in {"find_or_create_product", "changes_since"}:
        codes.append("module_not_installed")
    inputs = {i["value_type"] for i in spec["inputs"]}
    outputs = {o["value_type"] for o in spec["outputs"]}
    if "artifact_handle" in inputs:
        codes.append("artifact_input_unavailable")
    if "artifact_handle" in outputs:
        codes.append("artifact_output_unavailable")
    return codes


def operation(spec: dict[str, Any]) -> dict[str, Any]:
    write = spec["kind"] == "action"
    op: dict[str, Any] = {
        "operation_id": spec["operation_id"],
        "display_name": spec["display_name"],
        "description": spec["description"],
        "operation_kind": spec["kind"],
        "category": CATEGORY,
        "connection_type_ids": [CONNECTION_TYPE_ID],
        "workflow_visible": True,
    }
    if write:
        op["effect_kind"] = f"odoo_{spec['operation_id']}"
    outputs = list(spec["outputs"]) + (effect_outputs() if write else [])
    op["inputs"] = spec["inputs"]
    op["outputs"] = outputs
    op["result_fields"] = [f"result.{o['name']}" for o in outputs]
    op["error_codes"] = errors_for(spec)
    return op


ACTION_PARAM_TYPES = {
    "connection_ref": "connection_ref",
    "text": "string",
    "integer": "integer",
    "number": "number",
    "boolean": "boolean",
    "object": "object",
    "array": "array",
    "json": "object",
    "artifact_handle": "artifact_handle",
}


def action_for(op: dict[str, Any]) -> dict[str, Any]:
    write = op["operation_kind"] == "action"
    action: dict[str, Any] = {
        "action_id": op["operation_id"],
        "title": op["display_name"],
        "description": op["description"],
        "required_scopes": ["extension:invoke"],
        "handler": {"mode": "extension"},
    }
    if write:
        action["command_type"] = "invoke_extension_action"
    action["mutates_platform"] = write
    action["workflow_visible"] = True
    action["parameters"] = [
        {
            "name": i["name"],
            "type": ACTION_PARAM_TYPES[i["value_type"]],
            "required": bool(i.get("required")),
        }
        for i in op["inputs"]
    ]
    action["result_fields"] = [o["name"] for o in op["outputs"]]
    action["error_codes"] = list(op["error_codes"])
    return action


def widget_for(item: dict[str, Any]) -> str:
    schema = item.get("schema") or {}
    if schema.get("enum"):
        return "select"
    if item["name"] in TEXTAREA_INPUTS:
        return "textarea"
    vt = item["value_type"]
    if vt in {"object", "array", "json"}:
        return "json"
    if vt == "boolean":
        return "boolean"
    if vt in {"integer", "number"}:
        return "number"
    return "text"


FORM_PLACEHOLDERS = {
    (
        "create_customer_invoice",
        "lines",
    ): '[{"product_code":"PRODUCT01","quantity":2,"price_unit":12.5}]',
    ("find_or_create_partner", "name"): "Example customer Ltd",
    ("find_or_create_product", "name"): "Example product",
    ("changes_since", "since"): "2026-01-01 00:00:00",
}


def form_for(op: dict[str, Any]) -> dict[str, Any]:
    fields = []
    for item in op["inputs"]:
        if item["value_type"] == "connection_ref":
            continue
        if item["value_type"] == "artifact_handle":
            fields.append(
                {
                    "name": item["name"],
                    "label": "File",
                    "widget_type": "artifact_picker",
                    "required": bool(item.get("required")),
                    "help_text": FILE_FIELD_HELP,
                }
            )
            continue
        schema = item.get("schema") or {}
        field: dict[str, Any] = {
            "name": item["name"],
            "label": schema.get("title") or item["name"],
            "widget_type": widget_for(item),
            "required": bool(item.get("required")),
        }
        if schema.get("description"):
            field["help_text"] = schema["description"][:400]
        if schema.get("enum"):
            words = op_specs.OPTION_LABELS.get(item["name"], {})
            field["options"] = [{"label": words.get(v, str(v)), "value": v} for v in schema["enum"]]
        example = FORM_PLACEHOLDERS.get((op["operation_id"], item["name"]))
        if example is not None:
            field["placeholder"] = example
        fields.append(field)
    return {"operation_id": op["operation_id"], "title": op["display_name"], "fields": fields}


def artifact_policies(ops: list[dict[str, Any]]) -> list[dict[str, Any]]:
    policies: list[dict[str, Any]] = []
    for op in ops:
        file_inputs = [i for i in op["inputs"] if i["value_type"] == "artifact_handle"]
        if file_inputs:
            policies.append(
                {
                    "operation_id": op["operation_id"],
                    "inputs": [
                        {
                            "kind": "artifact",
                            "value_type": "artifact_handle",
                            "binding_key": UPLOAD_BINDING,
                            "field": i["name"],
                            "required": bool(i.get("required")),
                            "max_size_bytes": MAX_UPLOAD_BYTES,
                        }
                        for i in file_inputs
                    ],
                }
            )
    policies.append(
        {
            "operation_id": "download_attachment",
            "outputs": [
                {
                    "kind": "artifact",
                    "value_type": "artifact_handle",
                    "binding_key": DOWNLOAD_BINDING,
                    "filename": DOWNLOAD_FILENAME,
                    "content_type": DOWNLOAD_CONTENT_TYPE,
                    "max_size_bytes": MAX_DOWNLOAD_BYTES,
                    "retention_class": "run_window",
                }
            ],
        }
    )
    policies.append(
        {
            "operation_id": "export_records",
            "outputs": [
                {
                    "kind": "artifact",
                    "value_type": "artifact_handle",
                    "binding_key": EXPORT_BINDING,
                    "filename": EXPORT_FILENAME,
                    "content_type": EXPORT_CONTENT_TYPE,
                    "max_size_bytes": MAX_EXPORT_BYTES,
                    "max_size_env": "FS_EXTENSION_ARTIFACT_MAX_BYTES",
                    "retention_class": "run_window",
                }
            ],
        }
    )
    return policies


def external_effects(ops: list[dict[str, Any]]) -> list[dict[str, Any]]:
    return [
        {
            "operation_id": op["operation_id"],
            "effect_kind": op["effect_kind"],
            "channel": CHANNEL,
            "idempotency": "required",
            "test_mode_behavior": "suppress",
        }
        for op in ops
        if op["operation_kind"] == "action"
    ]


def dump(path: Path, payload: Any) -> None:
    text = yaml.safe_dump(payload, sort_keys=False, allow_unicode=True, width=100)
    path.write_text(GENERATED_HEADER + text, encoding="utf-8")


def splice_effects(effects: list[dict[str, Any]]) -> None:
    """Replace ``external_effects`` in extension.yaml, keeping every other key and its order."""
    manifest = ROOT / "extension.yaml"
    data = yaml.safe_load(manifest.read_text(encoding="utf-8"))
    rebuilt: dict[str, Any] = {}
    for key, value in data.items():
        if key == "runtime" and "external_effects" not in rebuilt:
            rebuilt["external_effects"] = effects
        if key != "external_effects":
            rebuilt[key] = value
    rebuilt.setdefault("external_effects", effects)
    manifest.write_text(
        yaml.safe_dump(rebuilt, sort_keys=False, allow_unicode=True, width=100), encoding="utf-8"
    )


def outputs() -> dict[str, Any]:
    specs = op_specs.operations()
    ops = [operation(spec) for spec in specs]
    names = [op["display_name"] for op in ops]
    if len(names) != len(set(names)):
        raise SystemExit("duplicate step titles")
    return {
        "specs": specs,
        "operations": ops,
        "actions": [action_for(op) for op in ops],
        "forms": [form_for(op) for op in ops],
        "artifact_policies": artifact_policies(ops),
        "effects": external_effects(ops),
        "api_page": build_ui_pages.api_page(ops, specs),
        "changelog_page": build_ui_pages.changelog_page(),
    }


def main() -> None:
    built = outputs()
    dump(ROOT / "contracts" / "operation_manifest.yaml", {"operations": built["operations"]})
    dump(ROOT / "contracts" / "step_ui_manifest.yaml", {"forms": built["forms"]})
    dump(
        ROOT / "contracts" / "artifact_policies.yaml",
        {"artifact_policies": built["artifact_policies"]},
    )
    dump(ROOT / "ui" / "actions" / "actions.yaml", {"actions": built["actions"]})
    for name, key in (("odoo-api.yaml", "api_page"), ("changelog.yaml", "changelog_page")):
        build_ui_pages.dump_page(ROOT / "ui" / "pages" / name, GENERATED_HEADER, built[key])
    splice_effects(built["effects"])
    print(f"{len(built['operations'])} operations, {len(built['effects'])} external effects")


if __name__ == "__main__":
    main()
